// Lists reviews/grid/ in the Selectel bucket, resizes each image to ~600px
// long edge (webp, normalizing the mixed .webp/.jpg sources), re-uploads to
// reviews/grid-600/, and writes content/reviews-grid.ts with the resulting
// filename + dimension list.
//
// Re-run whenever the bucket's reviews/grid/ contents change:
//   node --env-file=.env scripts/generate-reviews-grid.mjs
import path from "node:path";
import { fileURLToPath } from "node:url";
import { writeFile } from "node:fs/promises";
import { ListObjectsV2Command, GetObjectCommand, PutObjectCommand } from "@aws-sdk/client-s3";
import sharp from "sharp";
import { s3Bucket, s3Client, s3PublicBaseUrl, streamToBuffer } from "./s3-client.mjs";

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const SOURCE_PREFIX = "reviews/grid/";
const TARGET_PREFIX = "reviews/grid-600/";

async function listSourceKeys() {
  const keys = [];
  let continuationToken;
  do {
    const page = await s3Client.send(
      new ListObjectsV2Command({
        Bucket: s3Bucket,
        Prefix: SOURCE_PREFIX,
        ContinuationToken: continuationToken,
      }),
    );
    for (const obj of page.Contents ?? []) {
      // Skip the "directory marker" object some S3 UIs create for a prefix.
      if (obj.Key !== SOURCE_PREFIX && obj.Size && obj.Size > 0) {
        keys.push(obj.Key);
      }
    }
    continuationToken = page.IsTruncated ? page.NextContinuationToken : undefined;
  } while (continuationToken);
  return keys;
}

async function processOne(key) {
  const getResult = await s3Client.send(new GetObjectCommand({ Bucket: s3Bucket, Key: key }));
  const original = await streamToBuffer(getResult.Body);

  const baseName = path.basename(key).replace(/\.[^.]+$/, "");
  const targetKey = `${TARGET_PREFIX}${baseName}.webp`;

  const resized = sharp(original).resize({
    width: 600,
    height: 600,
    fit: "inside",
    withoutEnlargement: true,
  });
  const outputBuffer = await resized.toFormat("webp", { quality: 80 }).toBuffer();
  const { width, height } = await sharp(outputBuffer).metadata();

  await s3Client.send(
    new PutObjectCommand({
      Bucket: s3Bucket,
      Key: targetKey,
      Body: outputBuffer,
      ContentType: "image/webp",
    }),
  );

  return { file: `${baseName}.webp`, width, height };
}

async function main() {
  const keys = await listSourceKeys();
  console.log(`Found ${keys.length} objects under ${SOURCE_PREFIX}`);
  if (keys.length === 0) {
    throw new Error(`No objects found under ${SOURCE_PREFIX} — check S3_BUCKET/prefix.`);
  }

  const results = [];
  for (const key of keys) {
    process.stdout.write(`  processing ${key} ... `);
    const result = await processOne(key);
    results.push(result);
    console.log(`-> ${TARGET_PREFIX}${result.file} (${result.width}x${result.height})`);
  }

  const outPath = path.join(ROOT, "content", "reviews-grid.ts");
  const contents =
    `// GENERATED by scripts/generate-reviews-grid.mjs — do not hand-edit.\n` +
    `// Re-run: node --env-file=.env scripts/generate-reviews-grid.mjs\n\n` +
    `export const reviewsGridBaseUrl = ${JSON.stringify(`${s3PublicBaseUrl.replace(/\/+$/, "")}/${TARGET_PREFIX}`)};\n\n` +
    `export const reviewsGridImages = ${JSON.stringify(results, null, 2)} as const;\n`;

  await writeFile(outPath, contents, "utf8");
  console.log(`\nWrote ${results.length} entries to content/reviews-grid.ts`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
